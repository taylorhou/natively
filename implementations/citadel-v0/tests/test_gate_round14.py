def test_a_mirror_intent_terminates_its_audit_only_after_the_mirror_checks(tmp_path, capsys):
    """r14b finding 4, under a standing mirror intent at "truncated": the audit
    entry landed short of only its newline, the retained prefix valid, and a
    non-prefix partial line appended past it. Before, the newline was written and
    the mirror stage then refused. Now: ledger.prose.mismatch before the write,
    the JSONL and the marker byte-identical; twice. The partial line removed, the
    resume terminates the audit, regenerates its line and completes."""
    a, b, wa, wb, fake, clock, intent, marker = _mirror_repair_at_truncated(tmp_path)
    _torn_audit(b, intent, "unterminated")
    jsonl, mirror = b.ledger.path, b.ledger.prose_path
    torn_jsonl, retained = jsonl.read_bytes(), mirror.read_bytes()
    # the mirror: the retained prefix plus the line the completed run regenerated,
    # the audit's own line removed with its newline (`_torn_audit`)
    assert not torn_jsonl.endswith(b"\n") and retained.endswith(b"\n")
    assert len(retained) > intent["truncate_to"]
    bad = retained + b"zzz"
    mirror.write_bytes(bad)
    markers = {p: p.read_bytes() for p in b.state.glob("ledger-repair-pending*.json")}
    assert markers == {marker: marker.read_bytes()}
    for _retry in range(2):
        assert main([*_argv(b), "ledger", "repair"]) == 2
        out, err = capsys.readouterr()
        assert "ledger.prose.mismatch" in err and "not a prefix" in err, err
        assert "; terminated" not in err and "terminated" not in out  # no newline written
        assert jsonl.read_bytes() == torn_jsonl and mirror.read_bytes() == bad
        assert {p: p.read_bytes() for p in b.state.glob("ledger-repair-pending*.json")} == markers
    mirror.write_bytes(retained)
    assert main([*_argv(b), "ledger", "repair"]) == 0
    out, err = capsys.readouterr()
    assert "terminated" in err
    assert jsonl.read_bytes() == torn_jsonl + b"\n"
    assert _no_markers(b) and main([*_argv(b), "ledger", "verify"]) == 0
    assert _actions(b).count("ledger.mirror_truncated") == 1
    assert _actions(b).count("ledger.tail_truncated") == 0
