# ---- T6. every ledger append goes through the one checked helper (ORDERING) -----------------


def _append_sites(tree: ast.AST) -> set[str]:
    """The enclosing function of every `<...>.ledger.append(...)` / `Ledger.append(...)`
    call in a module."""
    out: set[str] = set()
    for fn in ast.walk(tree):
        if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for node in ast.walk(fn):
            if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)):
                continue
            if node.func.attr != "append":
                continue
            v = node.func.value
            if (isinstance(v, ast.Attribute) and v.attr == "ledger") or (
                isinstance(v, ast.Name) and v.id in ("Ledger", "ledger")
            ):
                out.add(fn.name)
    return out


