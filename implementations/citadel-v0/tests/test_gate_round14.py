def _store_stage_at_truncated_over_a_forged_audit(tmp_path, store: str):
    """b connected to a, its feed (or denial store) written BEFORE its last
    completion — an info a sent, its ack stored, so that completion is anchored —
    and that completion then edited into the `<store>.repaired` record of a
    marker at step "truncated" (the chain link intact, the mirror line removed):
    the loader alone reads the audit as landed. Returns (b, the store path, the
    verb, the audit action, the marker, the anchored msg_id)."""
