@pytest.mark.parametrize("how", ["lines-blank", "all-spaces"], ids=["lines-blank", "all-spaces"])
@pytest.mark.parametrize("step", STEPS)
def test_a_resumed_mirror_repair_validates_the_retained_prose_before_any_cut(
    tmp_path, capsys, step, how
):
    """T3 (a): a standing mirror intent at each step, and the prose prefix the intent
    retains replaced by whitespace of EQUAL length (every line blank with its
    newline kept, so the recorded suffix hash still matches; or all spaces): the
    resume is ledger.prose.mismatch naming the line (or the cut point), nothing cut,
    the marker standing at its step, both files and the marker byte-identical, no
    audit added. The prefix restored, the resume completes with exactly one audit."""
    a, b, wa, wb, fake, clock = _with_history_over_mail(tmp_path)
    jsonl, mirror = b.ledger.path, b.ledger.prose_path
    _tear_mirror(mirror, "tail")
    tail = b.ledger.excess_prose()
    size = mirror.stat().st_size
    intent = {
        "step": "intent",
        "file": "ledger.prose.txt",
        "truncate_to": size - len(tail),
        "bytes": len(tail),
        "tail_sha256": "sha256:" + sha256_hex(tail),
        "intent_id": new_id("rpr"),
        "ts": b.ts(),
    }
    if step != "intent":
        mirror.write_bytes(mirror.read_bytes()[: intent["truncate_to"]])
        intent["step"] = "truncated"
    if step == "audited":
        audit = b.ledger.append(
            ts=b.ts(),
            actor="solo",
            grant_id=None,
            action="ledger.mirror_truncated",
            params_hash=intent["tail_sha256"],
            outcome="recorded",
            detail=f"truncated {len(tail)} bytes; intent {intent['intent_id']}",
            intent_id=intent["intent_id"],
        )
        intent = {**intent, "step": "audited", "audit_hash": entry_hash(audit)}
    marker = _write_marker(b, intent)
    data, to = mirror.read_bytes(), intent["truncate_to"]
    assert to > 0 and data[:to].endswith(b"\n")
    if how == "lines-blank":
        blank = bytes(0x0A if c == 0x0A else 0x20 for c in data[:to])
    else:
        blank = b" " * to
    mirror.write_bytes(blank + data[to:])
    audits = _actions(b).count("ledger.mirror_truncated") if step == "audited" else 0
    before = (jsonl.read_bytes(), mirror.read_bytes(), marker.read_bytes())
    with pytest.raises(IntegrityError) as e:
        b.ledger.check_prose_prefix(to, b.ledger.check())
    assert e.value.reason == "ledger.prose.mismatch" and str(mirror) in str(e.value)
    assert ("prose line 0" if how == "lines-blank" else "cut point") in str(e.value)
    assert main([*_argv(b), "ledger", "repair"]) == 2
    err = capsys.readouterr().err
    assert "ledger.prose.mismatch" in err and str(mirror) in err
    assert "intent_mismatch" not in err and "truncated" not in capsys.readouterr().out
    assert (jsonl.read_bytes(), mirror.read_bytes(), marker.read_bytes()) == before
    assert json.loads(marker.read_text())["step"] == step
    assert jsonl.read_bytes().count(b"ledger.mirror_truncated") == audits
    # the prefix restored: the resume finishes from its step, one audit in all
    mirror.write_bytes(data)
    assert main([*_argv(b), "ledger", "repair"]) == 0
    assert _no_markers(b) and _actions(b).count("ledger.mirror_truncated") == 1
    assert main([*_argv(b), "ledger", "verify"]) == 0
    wa.send(a.compose_info(b.card, "after"))
    assert wb.poll_once()["applied"] == 1


def _audited_stage(tmp_path, stage: str):
    """A ledger repair marker at step "audited" — the ledger's own tail marker, the
    nested tail marker under a standing mirror intent, or the mirror marker — with
    the stage's audit appended in full (the JSONL line and its prose line landed).
    Returns (b, the intent, its marker, the expected audit counts)."""
    if stage == "mirror":
        a, b, wa, wb, fake, clock, intent, marker = _mirror_repair_at_truncated(tmp_path)
        b._repair_active = "ledger"
        b.ledger.append(
            ts=b.ts(),
            actor="solo",
            grant_id=None,
            action="ledger.mirror_truncated",
            params_hash=intent["tail_sha256"],
            outcome="recorded",
            detail=f"truncated {intent['bytes']} bytes; intent {intent['intent_id']}",
            intent_id=intent["intent_id"],
        )
        b._repair_active = None
        counts = {"ledger.tail_truncated": 0, "ledger.mirror_truncated": 1}
    else:
        b, intent, marker, _mirror_marker = _tail_stage_after_its_audit(
            tmp_path, nested=stage == "nested"
        )
        counts = {"ledger.tail_truncated": 1, "ledger.mirror_truncated": int(stage == "nested")}
    intent = {**intent, "step": "audited", "audit_hash": entry_hash(b.ledger.entries()[-1])}
    marker.write_text(json.dumps(intent), encoding="utf-8")
    assert b.ledger.verify()
