def _never(att):
    pytest.fail(f"nothing to fetch, yet {att} was fetched")


def _unavailable(row: dict, *needles: str) -> None:
    """The row is an INCOMPLETE FETCH: body "", truncated true, the reason naming
    every needle; the adapter reads it so (`RawMail.truncated`, `unavailable`)."""
    assert row["body"] == "" and row["truncated"] is True, row
    for n in needles:
        assert n in row["body_unavailable"], (n, row["body_unavailable"])
    (mail,) = parse_thread_json(json.dumps([row]))
    assert (
        mail.truncated is True and mail.body == "" and mail.unavailable == row["body_unavailable"]
    )


def _complete(row: dict, body: str) -> None:
    assert row["body"] == body and row["truncated"] is False and "body_unavailable" not in row
    (mail,) = parse_thread_json(json.dumps([row]))
    assert mail.truncated is False and mail.unavailable == "" and mail.body == body


